package com.exanthiax.ecominions.minions.model

import com.willfp.eco.core.blocks.TestableBlock
import org.bukkit.Material

/** How a mined block comes back. */
enum class RestoreMode {
    /** Put back exactly as it was, after the minion's regen delay. */
    REGEN,

    /** Placed again as a young plant, which then ripens in the world. */
    REPLANT,

    /** Felled: the block is cleared, and a sapling is planted to grow a new one. */
    TREE
}

/**
 * One `blocks/` definition: what a block *is*, and what is placed to restore it.
 *
 * Facts only. What a minion does with the block is its type's business, so an
 * oak log is felled by a woodcutter and regenerated by a miner from this same
 * definition. [restore] is the escape hatch for the rare block that needs to
 * override its minion.
 */
data class MinionBlock(
    val id: String,
    val lookup: String,
    val block: TestableBlock,
    /** Overrides the minion type's policy for this one block. Null means the type decides. */
    val restore: RestoreMode?,
    /** What self-seeding places. Null when nothing can be planted for this block. */
    val plant: TestableBlock?,
    /** The canopy of the grown tree. Required by [RestoreMode.TREE]. */
    val leaves: TestableBlock?,
    /** What must be underneath to plant. Null means any solid block will do. */
    val surface: TestableBlock?,
    /** Overrides which shape in `trees.json` this block grows as. */
    val treePattern: String?,
    /** Item ids credited during offline catch-up, for blocks whose drops cannot be read. */
    val drops: List<String>,
    /**
     * Whether a minion may target this block at all.
     *
     * False for blocks that break wrong - amethyst buds, dripstone, vines - so
     * no minion can be configured onto them however it is written.
     */
    val mineable: Boolean = true,
    /**
     * Whether this block grows upward in a column, like sugar cane or bamboo.
     *
     * A column is only ever cut at its base, taking the whole stack in one action.
     */
    val stackedColumn: Boolean = false,
    /**
     * The id this block really means when targeted, e.g. a seed targets its crop.
     *
     * An id rather than a resolved block, because it is looked up against the
     * `blocks/` catalog, which is not loaded yet while this is being parsed.
     */
    val promotesTo: String? = null,
    /**
     * The plain material this definition names, or null if it is a custom block.
     *
     * Resolved by the loader rather than computed here, because the model layer
     * stays server-free - and resolved once, so the per-tick target scan can
     * index by it instead of walking every definition.
     */
    val vanillaMaterial: Material? = null,
    /** XP one break of this block is worth, or null for none. */
    val experience: IntRange? = null
) {
    val isPlantable: Boolean
        get() = plant != null

    /** The `trees.json` key to grow this block with. */
    val patternKey: String
        get() = treePattern ?: id

    companion object {
        /** What an undefined block does: come back as it was. */
        fun regenDefault(id: String, lookup: String, block: TestableBlock) = MinionBlock(
            id = id,
            lookup = lookup,
            block = block,
            restore = null,
            plant = null,
            leaves = null,
            surface = null,
            treePattern = null,
            drops = emptyList()
        )
    }
}
